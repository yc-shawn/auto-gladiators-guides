const getCardFromSections = (id: string, sections: SectCardSection[]): SectCard => {
  for (const section of sections) {
    const card = section.cards.find((candidate) => candidate.id === id);
    if (card) return card;
  }

  throw new Error(`Missing shared sect card: ${id}`);
};

